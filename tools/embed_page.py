"""Copies Web APP/index.html into the firmware as a C string.

The Arduino IDE only compiles files inside the sketch folder, so the page has
to be turned into a header. Run this after every change to index.html:

    python tools/embed_page.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "Web APP" / "index.html"
DST = ROOT / "Microcontroler/Main/sketch_oct2a/src/Drivers/WebDriver/WebPage.h"
DELIM = "PAGE"

html = SRC.read_text(encoding="utf-8")
if f"){DELIM}\"" in html:
    raise SystemExit(f"index.html contains ){DELIM}\" which would end the raw string early")

DST.write_text(
    "// GENERATED by tools/embed_page.py from Web APP/index.html - do not edit by hand.\n"
    "#ifndef WEB_PAGE_H\n"
    "#define WEB_PAGE_H\n\n"
    f'static const char WEB_PAGE[] = R"{DELIM}(' + html + f'){DELIM}";\n\n'
    "#endif\n",
    encoding="utf-8",
    newline="\n",
)
print(f"Wrote {DST.relative_to(ROOT)} ({len(html.encode('utf-8'))} bytes of HTML)")
